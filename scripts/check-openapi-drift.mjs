#!/usr/bin/env node

/**
 * OpenAPI Drift Detection Script
 * Verifies that packages/api-client/src/generated/schema.ts is 100% in sync
 * with contracts/http/openapi.yaml.
 */

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const contractPath = path.join(rootDir, "contracts", "http", "openapi.yaml");
const generatedPath = path.join(
  rootDir,
  "packages",
  "api-client",
  "src",
  "generated",
  "schema.ts",
);

function normalize(str) {
  return str.replace(/\r\n/g, "\n").trim();
}

async function run() {
  console.log("🔍 Checking OpenAPI drift...");
  console.log(`- Contract: ${contractPath}`);
  console.log(`- Generated: ${generatedPath}`);

  let existingCode = "";
  try {
    existingCode = await fs.readFile(generatedPath, "utf-8");
  } catch (err) {
    console.error(`❌ Missing generated schema file at ${generatedPath}:`, err.message);
    console.error("👉 Run 'pnpm generate:api-client' to generate the client schema.");
    process.exit(1);
  }

  let freshlyGeneratedCode = "";
  try {
    const contractUrl = new URL(`file:///${contractPath.replace(/\\/g, "/")}`);
    const ast = await openapiTS(contractUrl);
    const header = `/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n`;
    freshlyGeneratedCode = header + astToString(ast);
  } catch (err) {
    console.error("❌ Failed to parse OpenAPI YAML contract:", err);
    process.exit(1);
  }

  if (normalize(freshlyGeneratedCode) !== normalize(existingCode)) {
    console.error("\n❌ OpenAPI drift detected!");
    console.error("The generated TypeScript types in packages/api-client do not match contracts/http/openapi.yaml.");
    console.error("👉 Please run 'pnpm generate:api-client' and commit the updated schema.ts.\n");
    process.exit(1);
  }

  console.log("✅ OpenAPI generated schema is 100% in sync with contracts/http/openapi.yaml.\n");
  process.exit(0);
}

run().catch((err) => {
  console.error("Unhandled error during OpenAPI drift check:", err);
  process.exit(1);
});
